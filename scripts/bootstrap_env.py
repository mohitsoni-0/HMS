"""Write a fresh local ``.env`` with random keys, and a new RSA-3072 key under ``secrets/local/``.

The committed ``.env.example`` keys and ``secrets/dev`` RSA key are public, so they protect nothing. This
script replaces them for one checkout: the ``.env`` it writes holds only the secrets (docker compose loads
``.env.example`` first and lets ``.env`` override it, and host runs read ``.env`` from the project root).

- ``DJANGO_SECRET_KEY``: 64 URL-safe random characters.
- ``JWT_SIGNING_KEY``, ``PII_BLIND_INDEX_KEY``, ``IDEMPOTENCY_FINGERPRINT_KEY``: base64 of 32 random bytes.
- ``PII_ENCRYPTION_KEYS`` / ``PII_ACTIVE_KEY_ID``: a one-key AES-256 ring.
- ``API_RSA_PRIVATE_KEY_PATH``: a new RSA-3072 key (PKCS#8 PEM); docker compose mounts ``secrets/`` read-only.

It refuses to overwrite an existing ``.env`` or key without ``--force``. With ``--force`` an existing
``APP_PORT`` is kept unless ``--app-port`` is given. New keys cannot decrypt PII written with the old ones,
so reset the local database afterwards (``docker compose down -v``).

Usage::

    python scripts/bootstrap_env.py [--force] [--app-port 8001]
"""

import argparse
import base64
import json
import os
import secrets
import sys
from collections.abc import Sequence
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

ROOT = Path(__file__).resolve().parents[1]
KEY_BYTES = 32
RSA_KEY_BITS = 3072
RSA_PUBLIC_EXPONENT = 65537
RSA_KEY_FILE = "api_rsa_private.pem"
PII_KEY_ID = "local1"
# Read by the container's unprivileged user (uid 10001) through the bind mount, which does not map the
# host owner, so the key is readable like the committed dev key; the .env stays owner-only.
RSA_KEY_MODE = 0o644
ENV_FILE_MODE = 0o600


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    env_file = Path(args.env_file).resolve()
    secrets_dir = Path(args.secrets_dir).resolve()
    key_file = secrets_dir / RSA_KEY_FILE

    existing = [path for path in (env_file, key_file) if path.exists()]
    if existing and not args.force:
        names = ", ".join(str(path) for path in existing)
        sys.stderr.write(f"Refusing to overwrite {names}; pass --force to replace existing files.\n")
        return 1

    app_port = args.app_port or (_read_value(env_file, "APP_PORT") if env_file.exists() else None)
    secrets_dir.mkdir(parents=True, exist_ok=True)
    _write(key_file, _rsa_private_key_pem(), RSA_KEY_MODE)
    _write(env_file, render_env(_key_path_setting(key_file), app_port).encode(), ENV_FILE_MODE)

    sys.stdout.write(
        f"Wrote {env_file} and {key_file}.\n"
        "Data encrypted with the previous keys cannot be read any more: run `docker compose down -v`, then "
        "`./local_run.sh`.\n"
    )
    return 0


def render_env(rsa_key_path: str, app_port: str | None = None) -> str:
    """The ``.env`` text: freshly generated values for every key setting, plus APP_PORT when given."""
    lines = [
        "# Local secrets generated by scripts/bootstrap_env.py: never commit this file (git ignores it).",
        "# docker compose loads .env.example first; these values override its public DEV-ONLY keys.",
        "",
        "ENVIRONMENT=local",
        f"DJANGO_SECRET_KEY={secrets.token_urlsafe(48)}",
        f"JWT_SIGNING_KEY={_random_key()}",
        f"PII_ENCRYPTION_KEYS={json.dumps({PII_KEY_ID: _random_key()})}",
        f"PII_ACTIVE_KEY_ID={PII_KEY_ID}",
        f"PII_BLIND_INDEX_KEY={_random_key()}",
        f"IDEMPOTENCY_FINGERPRINT_KEY={_random_key()}",
        f"API_RSA_PRIVATE_KEY_PATH={rsa_key_path}",
    ]
    if app_port:
        lines += ["", "# Host port of the API (docker-compose.yml publishes 127.0.0.1:${APP_PORT:-8000})", f"APP_PORT={app_port}"]
    return "\n".join(lines) + "\n"


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="replace an existing .env and RSA key")
    parser.add_argument("--app-port", help="host port for the API, written as APP_PORT (default: keep or 8000)")
    parser.add_argument("--env-file", default=str(ROOT / ".env"), help="where to write the env file")
    parser.add_argument("--secrets-dir", default=str(ROOT / "secrets" / "local"), help="where to write the RSA key")
    args = parser.parse_args(argv)
    if args.app_port is not None and not (args.app_port.isdigit() and 0 < int(args.app_port) < 65536):
        parser.error("--app-port must be a TCP port number")
    return args


def _random_key() -> str:
    return base64.b64encode(secrets.token_bytes(KEY_BYTES)).decode()


def _rsa_private_key_pem() -> bytes:
    key = rsa.generate_private_key(public_exponent=RSA_PUBLIC_EXPONENT, key_size=RSA_KEY_BITS)
    return key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
    )


def _key_path_setting(key_file: Path) -> str:
    """Relative to the project root when inside it, which is what the container sees under /app."""
    try:
        return key_file.relative_to(ROOT).as_posix()
    except ValueError:
        return str(key_file)


def _read_value(env_file: Path, name: str) -> str | None:
    for line in env_file.read_text(encoding="utf-8").splitlines():
        key, separator, value = line.strip().partition("=")
        if separator and key.strip() == name:
            return value.strip() or None
    return None


def _write(path: Path, content: bytes, mode: int) -> None:
    """Write ``content`` to ``path`` with ``mode``, replacing any existing file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(descriptor, "wb") as handle:
        handle.write(content)
    os.chmod(path, mode)  # O_CREAT's mode is masked by the umask and ignored for an existing file


if __name__ == "__main__":
    sys.exit(main())
